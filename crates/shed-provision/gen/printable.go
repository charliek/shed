//go:build ignore

// printable.go writes src/printable_table.rs: the code point ranges Go's
// unicode.IsPrint accepts, which the provision contract defines as a
// printable character. shed-server judges answers with unicode.IsPrint, so
// the Rust reader takes its table from the same function rather than from a
// second Unicode database.
//
// Run from crates/shed-provision:
//
//	go run gen/printable.go > src/printable_table.rs && cargo fmt
//
// The build tag keeps it out of the Go module's packages (go list ./...,
// golangci-lint); it is only ever run by name.
package main

import (
	"fmt"
	"runtime"
	"unicode"
)

func main() {
	type span struct{ lo, hi rune }
	var spans []span
	open := false
	var lo rune
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		in := r <= unicode.MaxRune && unicode.IsPrint(r)
		switch {
		case in && !open:
			lo, open = r, true
		case !in && open:
			spans = append(spans, span{lo, r - 1})
			open = false
		}
	}
	fmt.Printf("// Generated by gen/printable.go from Go's unicode.IsPrint (%s, Unicode %s).\n", runtime.Version(), unicode.Version)
	fmt.Println("// Do not edit; regenerate with `go run gen/printable.go > src/printable_table.rs`.")
	fmt.Println()
	fmt.Printf("/// The Unicode version of [`PRINTABLE`].\npub(crate) const UNICODE_VERSION: &str = %q;\n\n", unicode.Version)
	fmt.Println("/// Inclusive code point ranges, sorted and disjoint, of the printable characters.")
	fmt.Println("#[rustfmt::skip]")
	fmt.Printf("pub(crate) const PRINTABLE: [(u32, u32); %d] = [\n", len(spans))
	for i, s := range spans {
		if i%4 == 0 {
			fmt.Print("    ")
		}
		fmt.Printf("(0x%04x, 0x%04x),", s.lo, s.hi)
		if i%4 == 3 || i == len(spans)-1 {
			fmt.Println()
		} else {
			fmt.Print(" ")
		}
	}
	fmt.Println("];")
}
