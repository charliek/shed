//! The contract's text rules: names, ids, times, printable characters, the
//! path and value rules, and the refused targets and variables. Each matches
//! `internal/delivery/text.go` rule for rule.

use crate::limits::{MAX_FINGERPRINT_BYTES, MAX_PATH_BYTES, MAX_VALUE_BYTES};
use crate::printable_table::PRINTABLE;
use crate::rules::Rule;

/// The Unicode version the printable table was generated from (Go's
/// `unicode.Version` at generation).
pub fn unicode_version() -> &'static str {
    crate::printable_table::UNICODE_VERSION
}

/// Whether `s` is a valid item or provider name:
/// `[a-z0-9][a-z0-9._-]{0,63}`.
pub fn valid_name(s: &str) -> bool {
    let b = s.as_bytes();
    !b.is_empty()
        && b.len() <= 64
        && (b[0].is_ascii_lowercase() || b[0].is_ascii_digit())
        && b[1..].iter().all(|c| {
            c.is_ascii_lowercase() || c.is_ascii_digit() || matches!(c, b'.' | b'_' | b'-')
        })
}

/// Whether `s` is a request id (or a machine or stream id): 32 lowercase hex
/// digits.
pub fn valid_id(s: &str) -> bool {
    s.len() == 32
        && s.bytes()
            .all(|c| c.is_ascii_digit() || (b'a'..=b'f').contains(&c))
}

/// Whether `s` is an env item's variable by its alphabet:
/// `[A-Z_][A-Z0-9_]{0,127}`.
pub fn valid_variable(s: &str) -> bool {
    let b = s.as_bytes();
    !b.is_empty()
        && b.len() <= 128
        && (b[0].is_ascii_uppercase() || b[0] == b'_')
        && b[1..]
            .iter()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || *c == b'_')
}

/// Whether `s` is a fingerprint: 1 to 64 of `[A-Za-z0-9_-]`.
pub fn valid_fingerprint(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_FINGERPRINT_BYTES
        && s.bytes()
            .all(|c| c.is_ascii_alphanumeric() || c == b'_' || c == b'-')
}

/// Whether `s` is a time in the contract's one form: RFC 3339 in UTC,
/// written with an upper-case `Z` and whole seconds
/// (`2026-11-23T10:00:00Z`), naming a real instant.
pub fn valid_time(s: &str) -> bool {
    parse_time(s).is_some()
}

/// Reads a time in the contract's one form as seconds since the Unix epoch.
pub fn parse_time(s: &str) -> Option<i64> {
    let b = s.as_bytes();
    if b.len() != 20 {
        return None;
    }
    let digits = |r: std::ops::Range<usize>| -> Option<i64> {
        let mut n = 0i64;
        for &c in &b[r] {
            if !c.is_ascii_digit() {
                return None;
            }
            n = n * 10 + i64::from(c - b'0');
        }
        Some(n)
    };
    if b[4] != b'-'
        || b[7] != b'-'
        || b[10] != b'T'
        || b[13] != b':'
        || b[16] != b':'
        || b[19] != b'Z'
    {
        return None;
    }
    let (year, month, day) = (digits(0..4)?, digits(5..7)?, digits(8..10)?);
    let (hour, minute, second) = (digits(11..13)?, digits(14..16)?, digits(17..19)?);
    if !(1..=12).contains(&month) || day < 1 || day > days_in_month(year, month) {
        return None;
    }
    if hour > 23 || minute > 59 || second > 59 {
        return None;
    }
    Some(days_from_civil(year, month, day) * 86_400 + hour * 3600 + minute * 60 + second)
}

/// Writes `unix` seconds in the contract's one form.
pub fn format_time(unix: i64) -> String {
    let days = unix.div_euclid(86_400);
    let secs = unix.rem_euclid(86_400);
    let (y, m, d) = civil_from_days(days);
    format!(
        "{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}Z",
        secs / 3600,
        secs % 3600 / 60,
        secs % 60
    )
}

fn days_in_month(year: i64, month: i64) -> i64 {
    match month {
        2 if (year % 4 == 0 && year % 100 != 0) || year % 400 == 0 => 29,
        2 => 28,
        4 | 6 | 9 | 11 => 30,
        _ => 31,
    }
}

// Howard Hinnant's civil-date algorithms.
fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let mp = (m + 9) % 12;
    let doy = (153 * mp + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

fn civil_from_days(z: i64) -> (i64, i64, i64) {
    let z = z + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    (yoe + era * 400 + i64::from(m <= 2), m, d)
}

/// Whether `c` is printable: a letter, mark, number, punctuation or symbol
/// (Unicode general categories L, M, N, P and S), or U+0020 SPACE — Go's
/// `unicode.IsPrint`, from a table generated by it (`gen/printable.go`).
pub fn printable_char(c: char) -> bool {
    let cp = c as u32;
    PRINTABLE
        .binary_search_by(|&(lo, hi)| {
            if hi < cp {
                std::cmp::Ordering::Less
            } else if lo > cp {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether every character of `s` is printable ([`printable_char`]).
pub fn printable(s: &str) -> bool {
    s.chars().all(printable_char)
}

/// Whether `s` holds a control character: U+0000 to U+001F and U+007F to
/// U+009F.
pub fn has_control(s: &str) -> bool {
    s.chars().any(char::is_control)
}

/// The env variables no item may set.
pub const REFUSED_VARIABLES: [&str; 12] = [
    "PATH",
    "HOME",
    "USER",
    "LOGNAME",
    "SHELL",
    "IFS",
    "ENV",
    "BASH_ENV",
    "HTTP_PROXY",
    "HTTPS_PROXY",
    "NO_PROXY",
    "ALL_PROXY",
];

/// The prefixes no item's variable may start with.
pub const REFUSED_VARIABLE_PREFIXES: [&str; 2] = ["LD_", "SHED_"];

/// Whether `name` is a variable the contract refuses, compared after
/// upper-casing ASCII letters (`path` is `PATH`, `ld_preload` starts `LD_`):
/// an answer's variable is upper case by its alphabet already; the
/// comparison without case is for a reader of a file a person wrote.
pub fn refused_variable(name: &str) -> bool {
    let up = name.to_ascii_uppercase();
    REFUSED_VARIABLES.contains(&up.as_str())
        || REFUSED_VARIABLE_PREFIXES.iter().any(|p| up.starts_with(p))
}

/// The paths under home no file item may land on.
pub const REFUSED_HOME_FILES: [&str; 3] = [
    ".ssh/authorized_keys",
    ".ssh/authorized_keys2",
    ".ssh/known_hosts",
];

/// The directory under home no file item may land on, nor anything under
/// it: the shed's user environment directory.
pub const REFUSED_HOME_TREE: &str = ".config/environment.d";

/// Whether `path` (canonical, relative to home) is a refused target.
pub fn refused_home_target(path: &str) -> bool {
    REFUSED_HOME_FILES.contains(&path)
        || path == REFUSED_HOME_TREE
        || path
            .strip_prefix(REFUSED_HOME_TREE)
            .is_some_and(|rest| rest.starts_with('/'))
}

/// Applies the path rules, in order, and returns the rule `path` breaks, or
/// `None` for a relative, canonical path.
pub fn check_path(path: &str) -> Option<Rule> {
    if path.is_empty() {
        return Some(Rule::PathEmpty);
    }
    if path.len() > MAX_PATH_BYTES {
        return Some(Rule::PathTooLong);
    }
    if !printable(path) {
        return Some(Rule::PathNotPrintable);
    }
    if path.contains('\\') {
        return Some(Rule::PathBackslash);
    }
    if path.starts_with('/') {
        return Some(Rule::PathAbsolute);
    }
    if path.ends_with('/') {
        return Some(Rule::PathTrailingSlash);
    }
    for seg in path.split('/') {
        match seg {
            "" => return Some(Rule::PathEmptySegment),
            "." => return Some(Rule::PathDotSegment),
            ".." => return Some(Rule::PathDotDotSegment),
            _ => {}
        }
    }
    None
}

/// Applies the env value rules, in order, and returns the rule `value`
/// breaks, or `None`.
pub fn check_value(value: &str) -> Option<Rule> {
    if value.is_empty() {
        return Some(Rule::ValueEmpty);
    }
    if value.len() > MAX_VALUE_BYTES {
        return Some(Rule::ValueTooLong);
    }
    if !printable(value) {
        return Some(Rule::ValueNotPrintable);
    }
    if value.starts_with(' ') || value.ends_with(' ') {
        return Some(Rule::ValueEdgeSpace);
    }
    None
}

/// Applies the variable rules, in order: the alphabet, then the refused
/// list.
pub fn check_variable(variable: &str) -> Option<Rule> {
    if !valid_variable(variable) {
        return Some(Rule::BadVariable);
    }
    if refused_variable(variable) {
        return Some(Rule::RefusedVariable);
    }
    None
}

/// Whether `s` is 1 to `max` bytes with no control character.
pub(crate) fn bounded_text(s: &str, max: usize) -> bool {
    !s.is_empty() && s.len() <= max && !has_control(s)
}

/// Whether `p` is an absolute, canonical path: `/`, or slash-separated
/// segments after a leading slash with no empty, `.` or `..` segment, no
/// trailing slash and no backslash.
pub(crate) fn canonical_absolute(p: &str) -> bool {
    if p == "/" {
        return true;
    }
    let Some(rest) = p.strip_prefix('/') else {
        return false;
    };
    !p.contains('\\') && rest.split('/').all(|seg| !matches!(seg, "" | "." | ".."))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn printable_matches_the_contracts_examples() {
        for c in [' ', 'a', 'Z', '0', '~', 'é', '中', '€', '\u{1F600}'] {
            assert!(printable_char(c), "{c:?}");
        }
        for c in [
            '\0', '\t', '\n', '\r', '\u{7f}', '\u{85}', '\u{9f}', '\u{a0}', '\u{200b}', '\u{202e}',
            '\u{2028}', '\u{3000}', '\u{e000}', '\u{feff}',
        ] {
            assert!(!printable_char(c), "{c:?}");
        }
        assert_eq!(unicode_version(), "17.0.0");
    }

    #[test]
    fn table_is_sorted_and_disjoint() {
        for w in PRINTABLE.windows(2) {
            assert!(w[0].0 <= w[0].1 && w[0].1 + 1 < w[1].0, "{w:?}");
        }
    }

    #[test]
    fn times() {
        assert!(valid_time("2026-11-23T10:00:00Z"));
        assert!(valid_time("2024-02-29T23:59:59Z"));
        for bad in [
            "2026-11-23T10:00:00z",
            "2026-11-23T10:00:00.5Z",
            "2026-11-23T10:00:00+00:00",
            "2026-02-30T10:00:00Z",
            "2025-02-29T10:00:00Z",
            "2026-11-23T24:00:00Z",
            "2026-11-23T10:00:60Z",
            "2026-11-23",
        ] {
            assert!(!valid_time(bad), "{bad}");
        }
        let t = parse_time("2026-11-23T10:00:30Z").unwrap();
        assert_eq!(format_time(t), "2026-11-23T10:00:30Z");
        assert_eq!(parse_time("1970-01-01T00:00:00Z"), Some(0));
    }

    #[test]
    fn paths_values_variables() {
        assert_eq!(
            check_path(".ssh/./authorized_keys"),
            Some(Rule::PathDotSegment)
        );
        assert_eq!(check_path("a//b"), Some(Rule::PathEmptySegment));
        assert_eq!(check_path("a/../b"), Some(Rule::PathDotDotSegment));
        assert_eq!(check_path("a b/c"), None);
        assert!(refused_home_target(".config/environment.d"));
        assert!(refused_home_target(".config/environment.d/x.conf"));
        assert!(!refused_home_target(".config/environment.dx"));
        assert_eq!(check_value(" x"), Some(Rule::ValueEdgeSpace));
        assert_eq!(check_value("a \"$b\" c"), None);
        assert_eq!(check_variable("LD_PRELOAD"), Some(Rule::RefusedVariable));
        assert_eq!(check_variable("ld_preload"), Some(Rule::BadVariable));
        assert!(refused_variable("ld_preload"));
        assert!(canonical_absolute("/"));
        assert!(canonical_absolute("/home/shed/x"));
        assert!(!canonical_absolute("/home/shed/"));
        assert!(!canonical_absolute("home"));
    }
}
